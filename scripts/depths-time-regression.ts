import { auraPackRangeForMedian, auraPacksForDepth } from '../src/engine/depths-rewards'
import { battleSpeedSkillTreeBonus, battleSpeedStructureBonus, depthsFloorSpeedBonus, effectiveDepthsBattleSpeed, estimateBattleSeconds, estimateDepthClearSeconds, inBattleAcceleration, MIN_DEPTHS_BATTLE_SECONDS, DEFAULT_DEPTHS_FLOOR_OVERHEAD_SECONDS } from '../src/engine/depths-time'

function assert(condition: unknown, message: string): asserts condition { if (!condition) throw new Error(message) }
function close(a: number, b: number, eps = 1e-9) { return Math.abs(a - b) <= eps }

assert(effectiveDepthsBattleSpeed(1, true) === 4, 'Floor 1 Battle Speed should be 3 + Chrono 1')
assert(effectiveDepthsBattleSpeed(100, true) === 4.25, 'Floor 100 Battle Speed should include +0.25')
assert(battleSpeedStructureBonus(7) === 1.75, 'Max Battle Speed structure should add +1.75')
assert(effectiveDepthsBattleSpeed(1, true, 7) === 5.75, 'Max structure Battle Speed mismatch')
assert(battleSpeedSkillTreeBonus(0) === 0, 'Skill Tree Battle Speed level 0 mismatch')
assert(battleSpeedSkillTreeBonus(1) === 0.5, 'Skill Tree Battle Speed level 1 mismatch')
assert(battleSpeedSkillTreeBonus(2) === 1, 'Skill Tree Battle Speed level 2 mismatch')
assert(battleSpeedSkillTreeBonus(3) === 1.5, 'Skill Tree Battle Speed level 3 mismatch')
assert(battleSpeedSkillTreeBonus(4) === 2.5, 'Skill Tree Battle Speed level 4 mismatch')
assert(effectiveDepthsBattleSpeed(1, true, 7, 4) === 8.25, 'Structure + Skill Tree + Chrono Battle Speed stack mismatch')
assert(depthsFloorSpeedBonus(1800) === 4.5, 'Depths floor Battle Speed bonus should cap at +4.5')
assert(effectiveDepthsBattleSpeed(5000, true) === 8.5, 'High-floor Battle Speed should cap at 8.5 with Chrono')
assert(inBattleAcceleration(9) === 1 && inBattleAcceleration(10) === 2, '10-attack acceleration mismatch')
assert(inBattleAcceleration(20) === 3 && inBattleAcceleration(40) === 5 && inBattleAcceleration(60) === 10, 'Long-battle acceleration mismatch')
assert(close(MIN_DEPTHS_BATTLE_SECONDS, 0.2), 'Attack phase minimum must remain 0.2s')
assert(close(DEFAULT_DEPTHS_FLOOR_OVERHEAD_SECONDS, 0.8), 'Default estimated floor transition is 0.8s')
assert(close(estimateBattleSeconds(1, 0, true), 1), '0-turn floor requires 0.2s minimum plus 0.8s transition')
assert(close(estimateBattleSeconds(1, 1, true), 1.05), 'One attack at speed 4 plus 0.8s transition')
assert(close(estimateBattleSeconds(1, 2, true), 1.3), 'Two attacks at speed 4 plus 0.8s transition')
assert(close(estimateBattleSeconds(1, 12, true), 3.425), 'Attack 10+ acceleration should still reduce timing')
assert(close(estimateBattleSeconds(1, 1, false), 0.8+1/3), 'No-Chrono one-attack time')
assert(close(estimateBattleSeconds(1, 1, true, 0, 0, 4), 1), 'Galaxy Chrono still uses 0.2s attack minimum plus transition')
assert(close(estimateDepthClearSeconds(3, 1, true), 3.15), 'Clear time must include 3 floor transitions')
assert(close(estimateDepthClearSeconds(3, 0, true), 3), 'Three 0-turn floors require minimum attack + transitions')
assert(close(estimateDepthClearSeconds(3, 1, true, 0, 0, 0, 0), 0.75), 'Explicit zero-transition mode must preserve attack-only timing')
assert(close(estimateBattleSeconds(1, 1, true, 0, 0, 0, 3), 3.25), '3-second adjustable overhead must be honored')
assert(effectiveDepthsBattleSpeed(1, false) === 3, 'Floor 1 Battle Speed without Chrono should be 3')
assert(effectiveDepthsBattleSpeed(1,true,0,0,4)===5,'Galaxy Chrono Shard adds +2 speed')
assert(effectiveDepthsBattleSpeed(1,true,0,0,1)===4.25,'Platinum Chrono Shard adds +1.25 speed')
assert(effectiveDepthsBattleSpeed(1,false,0,0,4)===3,'Disabled Chrono Shard cannot add speed')
assert(estimateBattleSeconds(1,5,true,0,0,4)<estimateBattleSeconds(1,5,true,0,0,0),'Upgraded Chrono must shorten battle time')
assert(estimateBattleSeconds(1, 1, false) > estimateBattleSeconds(1, 1, true), 'Chrono Shard should reduce estimated battle time')
assert(auraPacksForDepth(5001) - auraPacksForDepth(5000) === 882, 'Aura Pack reward should stay capped after floor 5000')
assert(auraPacksForDepth(22000) === 16872195, 'Aura Pack 22k capped reward mismatch')
const reward = auraPackRangeForMedian(13334)
assert(reward.medianDepth === 13334, 'Median depth mismatch')
assert(reward.auraPackLow === 7464783, 'Low Aura Pack mismatch')
assert(reward.auraPackMedian === 9228783, 'Median Aura Pack mismatch')
assert(reward.auraPackHigh === 10992783, 'High Aura Pack mismatch')
console.log('Depths speed/reward regression passed:', reward)
